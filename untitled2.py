import sqlite3
import pandas as pd

# Crear la conexión
conexion = sqlite3.connect("proyecto.db")
cursor = conexion.cursor()
print("Conexión realizada correctamente.")

# Crear la tabla
cursor.execute("""
CREATE TABLE IF NOT EXISTS buses (
    id_bus TEXT PRIMARY KEY,
    tipo_bus TEXT NOT NULL,
    capacidad INTEGER NOT NULL,
    combustible_litros REAL NOT NULL,
    estado TEXT NOT NULL
)
""")
conexion.commit()

# Insertar tres registros
datos_buses = [
    ("B1", "Pequeño", 32, 200.0, "Disponible"),
    ("B2", "Pequeño", 32, 200.0, "Disponible"),
    ("B5", "Grande", 38, 300.0, "Disponible")
]
cursor.executemany("""
INSERT OR REPLACE INTO buses
(id_bus, tipo_bus, capacidad, combustible_litros, estado)
VALUES ('B1', 'Pequeño', 32, 200.0, 'Disponible')
""", datos_buses)
conexion.commit()
print("Registros insertados correctamente.")

# Consultar todos los registros
consulta = "SELECT * FROM buses"
resultado = pd.read_sql_query(consulta, conexion)
print(resultado)

# Cerrar la conexión
conexion.close()
print("Conexión cerrada correctamente.")